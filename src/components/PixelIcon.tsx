export type IconName = keyof typeof ICONS

interface PixelIconProps {
  name: IconName
  size?: number
  className?: string
  /** Ohne Titel ist das Icon dekorativ und für Screenreader unsichtbar. */
  title?: string
}

export function PixelIcon({ name, size = 18, className = '', title }: PixelIconProps) {
  const rows = ICONS[name]
  const rects: { x: number; y: number; accent: boolean }[] = []
  rows.forEach((row, y) =>
    [...row].forEach((cell, x) => {
      if (cell === '#' || cell === '+') rects.push({ x, y, accent: cell === '+' })
    }),
  )
  return (
    <svg
      viewBox="0 0 12 12"
      width={size}
      height={size}
      className={`pixelated inline-block shrink-0 ${className}`}
      fill="currentColor"
      role={title ? 'img' : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
    >
      {rects.map((r) => (
        <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={1} height={1} opacity={r.accent ? 0.45 : 1} />
      ))}
    </svg>
  )
}
